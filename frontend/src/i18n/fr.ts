/** French sets a (non-breaking) space before ? ! : ; and inside « ». The entries above use plain spaces. */
function typography(text: string): string {
  return text.replace(/ ([?!:;»])/g, '\u00a0$1').replace(/« /g, '«\u00a0');
}

